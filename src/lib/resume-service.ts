import { Prisma } from "@prisma/client";
import { prisma } from "./db";
import { ResumeData, ResumeListItem, ResumeRecord, AdditionalKind, emptyResume } from "./types";

const parseList = (v: string): string[] => {
  try {
    const p = JSON.parse(v);
    return Array.isArray(p) ? p.map(String) : [];
  } catch {
    return [];
  }
};

const include = {
  personal: true,
  summary: true,
  experiences: { orderBy: { position: "asc" } },
  education: { orderBy: { position: "asc" } },
  skills: { orderBy: { position: "asc" } },
  projects: { orderBy: { position: "asc" } },
  certifications: { orderBy: { position: "asc" } },
  additional: { orderBy: { position: "asc" } },
} satisfies Prisma.ResumeInclude;

type FullResume = Prisma.ResumeGetPayload<{ include: typeof include }>;

function toRecord(r: FullResume): ResumeRecord {
  const base = emptyResume();
  const p = r.personal;
  return {
    id: r.id,
    name: r.name,
    createdAt: r.createdAt.toISOString(),
    updatedAt: r.updatedAt.toISOString(),
    data: {
      personal: p
        ? {
            fullName: p.fullName,
            title: p.title,
            email: p.email,
            phone: p.phone,
            location: p.location,
            linkedin: p.linkedin,
            github: p.github,
            portfolio: p.portfolio,
            photoUrl: p.photoUrl,
          }
        : base.personal,
      summary: r.summary?.content ?? "",
      experiences: r.experiences.map((e) => ({
        id: e.id,
        company: e.company,
        jobTitle: e.jobTitle,
        employmentType: e.employmentType,
        location: e.location,
        startDate: e.startDate,
        endDate: e.endDate,
        isCurrent: e.isCurrent,
        responsibilities: parseList(e.responsibilities),
        achievements: parseList(e.achievements),
      })),
      education: r.education.map((e) => ({
        id: e.id,
        degree: e.degree,
        institution: e.institution,
        location: e.location,
        startDate: e.startDate,
        endDate: e.endDate,
        description: e.description,
      })),
      skills: r.skills.map((s) => ({
        id: s.id,
        name: s.name,
        category: s.category,
        proficiency: s.proficiency,
      })),
      projects: r.projects.map((x) => ({
        id: x.id,
        name: x.name,
        technologies: x.technologies,
        description: x.description,
        url: x.url,
        githubUrl: x.githubUrl,
      })),
      certifications: r.certifications.map((c) => ({
        id: c.id,
        name: c.name,
        issuer: c.issuer,
        date: c.date,
        url: c.url,
      })),
      additional: r.additional.map((a) => ({
        id: a.id,
        kind: a.kind as AdditionalKind,
        title: a.title,
        items: parseList(a.items),
      })),
    },
  };
}

// Writes every section of `data` for `resumeId`. Row ids are generated by the DB
// (never reused from the client) so duplicates can never collide with the original.
async function writeChildren(tx: Prisma.TransactionClient, resumeId: string, d: ResumeData) {
  await tx.resumePersonalDetail.create({
    data: {
      resumeId,
      fullName: d.personal.fullName,
      title: d.personal.title,
      email: d.personal.email,
      phone: d.personal.phone,
      location: d.personal.location,
      linkedin: d.personal.linkedin,
      github: d.personal.github,
      portfolio: d.personal.portfolio,
      photoUrl: d.personal.photoUrl ?? null,
    },
  });
  await tx.resumeSummary.create({ data: { resumeId, content: d.summary } });
  if (d.experiences.length)
    await tx.resumeExperience.createMany({
      data: d.experiences.map((e, position) => ({
        resumeId,
        position,
        company: e.company,
        jobTitle: e.jobTitle,
        employmentType: e.employmentType,
        location: e.location,
        startDate: e.startDate,
        endDate: e.isCurrent ? "" : e.endDate,
        isCurrent: e.isCurrent,
        responsibilities: JSON.stringify(e.responsibilities),
        achievements: JSON.stringify(e.achievements),
      })),
    });
  if (d.education.length)
    await tx.resumeEducation.createMany({
      data: d.education.map((e, position) => ({
        resumeId,
        position,
        degree: e.degree,
        institution: e.institution,
        location: e.location,
        startDate: e.startDate,
        endDate: e.endDate,
        description: e.description,
      })),
    });
  if (d.skills.length)
    await tx.resumeSkill.createMany({
      data: d.skills.map((s, position) => ({
        resumeId,
        position,
        name: s.name,
        category: s.category,
        proficiency: s.proficiency,
      })),
    });
  if (d.projects.length)
    await tx.resumeProject.createMany({
      data: d.projects.map((p, position) => ({
        resumeId,
        position,
        name: p.name,
        technologies: p.technologies,
        description: p.description,
        url: p.url,
        githubUrl: p.githubUrl,
      })),
    });
  if (d.certifications.length)
    await tx.resumeCertification.createMany({
      data: d.certifications.map((c, position) => ({
        resumeId,
        position,
        name: c.name,
        issuer: c.issuer,
        date: c.date,
        url: c.url,
      })),
    });
  if (d.additional.length)
    await tx.resumeAdditionalSection.createMany({
      data: d.additional.map((a, position) => ({
        resumeId,
        position,
        kind: a.kind,
        title: a.title,
        items: JSON.stringify(a.items),
      })),
    });
}

export async function listResumes(): Promise<ResumeListItem[]> {
  const rows = await prisma.resume.findMany({
    orderBy: { updatedAt: "desc" },
    include: { personal: { select: { fullName: true, title: true } } },
  });
  return rows.map((r) => ({
    id: r.id,
    name: r.name,
    fullName: r.personal?.fullName ?? "",
    title: r.personal?.title ?? "",
    updatedAt: r.updatedAt.toISOString(),
    createdAt: r.createdAt.toISOString(),
  }));
}

export async function getResume(id: string): Promise<ResumeRecord | null> {
  const r = await prisma.resume.findUnique({ where: { id }, include });
  return r ? toRecord(r) : null;
}

export async function createResume(name: string, data: ResumeData): Promise<ResumeRecord> {
  const id = await prisma.$transaction(async (tx) => {
    const r = await tx.resume.create({ data: { name } });
    await writeChildren(tx, r.id, data);
    return r.id;
  });
  return (await getResume(id))!;
}

export async function saveResume(
  id: string,
  patch: { name?: string; data?: ResumeData },
): Promise<ResumeRecord | null> {
  const exists = await prisma.resume.findUnique({ where: { id }, select: { id: true } });
  if (!exists) return null;
  await prisma.$transaction(async (tx) => {
    // `updatedAt` is bumped on every save, even if only children changed.
    await tx.resume.update({
      where: { id },
      data: patch.name ? { name: patch.name } : { updatedAt: new Date() },
    });
    if (patch.data) {
      await tx.resumePersonalDetail.deleteMany({ where: { resumeId: id } });
      await tx.resumeSummary.deleteMany({ where: { resumeId: id } });
      await tx.resumeExperience.deleteMany({ where: { resumeId: id } });
      await tx.resumeEducation.deleteMany({ where: { resumeId: id } });
      await tx.resumeSkill.deleteMany({ where: { resumeId: id } });
      await tx.resumeProject.deleteMany({ where: { resumeId: id } });
      await tx.resumeCertification.deleteMany({ where: { resumeId: id } });
      await tx.resumeAdditionalSection.deleteMany({ where: { resumeId: id } });
      await writeChildren(tx, id, patch.data);
    }
  });
  return getResume(id);
}

export async function duplicateResume(id: string): Promise<ResumeRecord | null> {
  const src = await getResume(id);
  if (!src) return null;
  return createResume(`${src.name} (Copy)`.slice(0, 120), src.data);
}

export async function deleteResume(id: string): Promise<boolean> {
  const res = await prisma.resume.deleteMany({ where: { id } });
  return res.count > 0;
}
